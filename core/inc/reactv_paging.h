#ifndef _REACTV_PAGING_H_
#define _REACTV_PAGING_H_

#define AMD64_PAGE_SHIFT        12
#define AMD64_PAGE_SIZE         (1ULL << AMD64_PAGE_SHIFT)
#define AMD64_PAGE_MASK         (AMD64_PAGE_SIZE - 1)

/* 2MB large page mapped by a PDE */
#define AMD64_LARGE_PAGE_SHIFT  21
#define AMD64_LARGE_PAGE_SIZE   (1ULL << AMD64_LARGE_PAGE_SHIFT)
#define AMD64_LARGE_PAGE_MASK   (AMD64_LARGE_PAGE_SIZE - 1)

#define AMD64_PXI_SHIFT         39
#define AMD64_PPI_SHIFT         30
#define AMD64_PDI_SHIFT         21
#define AMD64_PTI_SHIFT         12
#define AMD64_TABLE_INDEX_MASK  0x1FF

#define AMD64_PXI(Address) ((ULONG)(((ULONG64)(Address) >> AMD64_PXI_SHIFT) & AMD64_TABLE_INDEX_MASK))
#define AMD64_PPI(Address) ((ULONG)(((ULONG64)(Address) >> AMD64_PPI_SHIFT) & AMD64_TABLE_INDEX_MASK))
#define AMD64_PDI(Address) ((ULONG)(((ULONG64)(Address) >> AMD64_PDI_SHIFT) & AMD64_TABLE_INDEX_MASK))
#define AMD64_PTI(Address) ((ULONG)(((ULONG64)(Address) >> AMD64_PTI_SHIFT) & AMD64_TABLE_INDEX_MASK))

/* Page table entry bits */
#define AMD64_PTE_PRESENT       0x0000000000000001ULL
#define AMD64_PTE_WRITE         0x0000000000000002ULL
#define AMD64_PTE_USER          0x0000000000000004ULL
#define AMD64_PTE_WRITE_THROUGH 0x0000000000000008ULL
#define AMD64_PTE_CACHE_DISABLE 0x0000000000000010ULL
#define AMD64_PTE_ACCESSED      0x0000000000000020ULL
#define AMD64_PTE_DIRTY         0x0000000000000040ULL
#define AMD64_PTE_LARGE_PAGE    0x0000000000000080ULL
#define AMD64_PTE_GLOBAL        0x0000000000000100ULL
#define AMD64_PTE_NO_EXECUTE    0x8000000000000000ULL

#define AMD64_PTE_ADDRESS_MASK  0x000FFFFFFFFFF000ULL

#endif /* _REACTV_PAGING_H_ */
