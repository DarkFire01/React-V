#define REACTV_VMCS_GUEST_LDTR_SELECTOR 0x0000080C
#define REACTV_VMCS_GUEST_TR_SELECTOR   0x0000080E

/* 16 bit host state. RPL and TI must be zero */
#define REACTV_VMCS_HOST_ES_SELECTOR    0x00000C00
#define REACTV_VMCS_HOST_CS_SELECTOR    0x00000C02
#define REACTV_VMCS_HOST_SS_SELECTOR    0x00000C04
#define REACTV_VMCS_HOST_DS_SELECTOR    0x00000C06
#define REACTV_VMCS_HOST_FS_SELECTOR    0x00000C08
#define REACTV_VMCS_HOST_GS_SELECTOR    0x00000C0A
#define REACTV_VMCS_HOST_TR_SELECTOR    0x00000C0C

/* 64 bit control */
#define REACTV_VMCS_MSR_BITMAP          0x00002004
#define REACTV_VMCS_LINK_POINTER        0x00002800
#define REACTV_VMCS_GUEST_IA32_PAT      0x00002804
#define REACTV_VMCS_GUEST_IA32_EFER     0x00002806
#define REACTV_VMCS_HOST_IA32_PAT       0x00002C00
#define REACTV_VMCS_HOST_IA32_EFER      0x00002C02

/* 32 bit control */
#define REACTV_VMCS_PINBASED_CONTROLS   0x00004000
#define REACTV_VMCS_PROCBASED_CONTROLS  0x00004002
#define REACTV_VMCS_EXCEPTION_BITMAP    0x00004004
