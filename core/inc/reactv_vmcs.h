/* Fn0000_0001_ECX */
#define AMD64_FEATURE_VMX               0x00000020

/* CONTROL AND CAPABILITY MSRS ************************************************/

#define AMD64_MSR_FEATURE_CONTROL       0x0000003A
#define AMD64_FEATURE_CONTROL_LOCK      0x0000000000000001ULL
#define AMD64_FEATURE_CONTROL_VMX_SMX   0x0000000000000002ULL
#define AMD64_FEATURE_CONTROL_VMX       0x0000000000000004ULL

#define AMD64_MSR_VMX_BASIC             0x00000480
#define AMD64_MSR_VMX_PINBASED_CTLS     0x00000481
#define AMD64_MSR_VMX_PROCBASED_CTLS    0x00000482
#define AMD64_MSR_VMX_EXIT_CTLS         0x00000483
#define AMD64_MSR_VMX_ENTRY_CTLS        0x00000484
#define AMD64_MSR_VMX_CR0_FIXED0        0x00000486
#define AMD64_MSR_VMX_CR0_FIXED1        0x00000487
#define AMD64_MSR_VMX_CR4_FIXED0        0x00000488
#define AMD64_MSR_VMX_CR4_FIXED1        0x00000489
#define AMD64_MSR_VMX_PROCBASED_CTLS2   0x0000048B
#define AMD64_MSR_VMX_TRUE_PINBASED     0x0000048D
#define AMD64_MSR_VMX_TRUE_PROCBASED    0x0000048E
#define AMD64_MSR_VMX_TRUE_EXIT         0x0000048F
#define AMD64_MSR_VMX_TRUE_ENTRY        0x00000490

/* VMCS revision identifier */
#define AMD64_VMX_BASIC_REVISION_MASK   0x000000007FFFFFFFULL
/* Bit 55: TRUE capability MSRs are supported and take precedence */
#define AMD64_VMX_BASIC_TRUE_CONTROLS   0x0080000000000000ULL

#define AMD64_CR4_VMXE                  0x0000000000002000ULL

/* EXECUTION CONTROLS *********************************************************/

/* Primary processor-based controls, Intel SDM vol 3 table 24-6 */
#define REACTV_PROC_HLT_EXITING         0x00000080
#define REACTV_PROC_USE_MSR_BITMAPS     0x10000000
#define REACTV_PROC_SECONDARY_CONTROLS  0x80000000

/* VM-exit controls, table 24-13. Host is 64-bit */
#define REACTV_EXIT_HOST_ADDRESS_SPACE  0x00000200
#define REACTV_EXIT_SAVE_IA32_EFER      0x00100000
#define REACTV_EXIT_LOAD_IA32_EFER      0x00200000

/* VM-entry controls, table 24-15 */
#define REACTV_ENTRY_IA32E_MODE_GUEST   0x00000200
#define REACTV_ENTRY_LOAD_IA32_EFER     0x00008000

/* VMCS FIELD ENCODINGS *******************************************************/

