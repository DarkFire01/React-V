#define REACTV_VMCS_EXIT_MSR_STORE_COUNT 0x0000400E
#define REACTV_VMCS_EXIT_MSR_LOAD_COUNT 0x00004010
#define REACTV_VMCS_ENTRY_CONTROLS      0x00004012
#define REACTV_VMCS_ENTRY_MSR_LOAD_COUNT 0x00004014
#define REACTV_VMCS_ENTRY_INTERRUPT_INFO 0x00004016
#define REACTV_VMCS_ENTRY_EXCEPTION_CODE 0x00004018
#define REACTV_VMCS_ENTRY_INSTRUCTION_LEN 0x0000401A
#define REACTV_VMCS_PROCBASED_CONTROLS2 0x0000401E

/* 32 bit read only */
#define REACTV_VMCS_INSTRUCTION_ERROR   0x00004400
#define REACTV_VMCS_EXIT_REASON         0x00004402
#define REACTV_VMCS_EXIT_INTERRUPT_INFO 0x00004404
#define REACTV_VMCS_EXIT_INSTRUCTION_LEN 0x0000440C

/* 32 bit guest state */
#define REACTV_VMCS_GUEST_ES_LIMIT      0x00004800
#define REACTV_VMCS_GUEST_CS_LIMIT      0x00004802
#define REACTV_VMCS_GUEST_SS_LIMIT      0x00004804
#define REACTV_VMCS_GUEST_DS_LIMIT      0x00004806
#define REACTV_VMCS_GUEST_FS_LIMIT      0x00004808
#define REACTV_VMCS_GUEST_GS_LIMIT      0x0000480A
#define REACTV_VMCS_GUEST_LDTR_LIMIT    0x0000480C
#define REACTV_VMCS_GUEST_TR_LIMIT      0x0000480E
#define REACTV_VMCS_GUEST_GDTR_LIMIT    0x00004810
#define REACTV_VMCS_GUEST_IDTR_LIMIT    0x00004812
#define REACTV_VMCS_GUEST_ES_ACCESS     0x00004814
#define REACTV_VMCS_GUEST_CS_ACCESS     0x00004816
#define REACTV_VMCS_GUEST_SS_ACCESS     0x00004818
#define REACTV_VMCS_GUEST_DS_ACCESS     0x0000481A
#define REACTV_VMCS_GUEST_FS_ACCESS     0x0000481C
#define REACTV_VMCS_GUEST_GS_ACCESS     0x0000481E
#define REACTV_VMCS_GUEST_LDTR_ACCESS   0x00004820
#define REACTV_VMCS_GUEST_TR_ACCESS     0x00004822
#define REACTV_VMCS_GUEST_INTERRUPTIBILITY 0x00004824
#define REACTV_VMCS_GUEST_ACTIVITY      0x00004826

/* Natural width guest state */
#define REACTV_VMCS_GUEST_CR0           0x00006800
#define REACTV_VMCS_GUEST_CR3           0x00006802
#define REACTV_VMCS_GUEST_CR4           0x00006804
