#define REACTV_VMCS_GUEST_ES_SELECTOR   0x00000800
#define REACTV_VMCS_GUEST_CS_SELECTOR   0x00000802
#define REACTV_VMCS_GUEST_SS_SELECTOR   0x00000804
#define REACTV_VMCS_GUEST_DS_SELECTOR   0x00000806
#define REACTV_VMCS_GUEST_FS_SELECTOR   0x00000808
